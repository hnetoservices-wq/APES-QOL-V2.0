// Bundles the reviewed UTF-8 translation table. No network or runtime dependency.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const rows = fs.readFileSync(path.join(__dirname, 'translations.tsv'), 'utf8').trimEnd().split(/\r?\n/).map(row => row.split('\t'));
const languages = rows.shift().slice(1);
const catalogs = Object.fromEntries(languages.map(code => [code, {}]));
for (const [index, row] of rows.entries()) {
  if (row.length !== 8 || row.some(cell => !cell.trim())) throw Error(`Incomplete translation row ${index + 2}`);
  const [key, ...values] = row;
  values.forEach((value, i) => {
    if (Object.hasOwn(catalogs[languages[i]], key)) throw Error(`Duplicate key: ${key}`);
    catalogs[languages[i]][key] = value;
  });
}
fs.mkdirSync(path.join(root, 'js/locales'), { recursive: true });
fs.writeFileSync(path.join(root, 'js/locales/catalogs.js'), '/* Generated by tools/build-locales.cjs; edit tools/translations.tsv. */\n(() => {\n  window.APES.localeCatalogs = ' + JSON.stringify(catalogs, null, 2) + ';\n})();\n');
console.log(`${rows.length} messages × ${languages.length} translated languages`);
